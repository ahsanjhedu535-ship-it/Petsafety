-- Run this in the Supabase SQL Editor before enabling form storage.
create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique check (char_length(email) <= 254),
  created_at timestamptz not null default now()
);
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 100),
  email text not null check (char_length(email) <= 254),
  subject text not null check (char_length(subject) <= 160),
  message text not null check (char_length(message) <= 5000),
  created_at timestamptz not null default now()
);
-- Keep these tables private. The service-role key is server-side only; never expose it in NEXT_PUBLIC variables.
alter table public.newsletter_subscribers enable row level security;
alter table public.contact_messages enable row level security;
